# ------------------------------------------------------------------ drawing

def fill(fb, x, y, w, h, v):
    x0, y0, x1, y1 = max(0, x), max(0, y), min(W, x + w), min(H, y + h)
    if x1 <= x0 or y1 <= y0:
        return
    row = bytes([v]) * (x1 - x0)
    for r in range(y0, y1):
        fb[r * W + x0:r * W + x1] = row


def frame(fb, x, y, w, h, v, t=2):
    fill(fb, x, y, w, t, v)
    fill(fb, x, y + h - t, w, t, v)
    fill(fb, x, y, t, h, v)
    fill(fb, x + w - t, y, t, h, v)


def text_w(s, scale):
    return len(s) * 6 * scale - scale


def text(fb, x, y, s, scale=2, v=255):
    for i, ch in enumerate(s):
        c = ord(ch) - 32
        if not 0 <= c < 95:
            continue
        for col in range(5):
            bits = FONT[c * 5 + col]
            for row in range(7):
                if bits >> row & 1:
                    fill(fb, x + (i * 6 + col) * scale, y + row * scale, scale, scale, v)


def centred(fb, cx, y, s, scale=2, v=255):
    text(fb, cx - text_w(s, scale) // 2, y, s, scale, v)
